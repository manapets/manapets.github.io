function toJson(p) {
  const images = [`/images/products/${p.id}-1.svg`, `/images/products/${p.id}-2.svg`, `/images/products/${p.id}-3.svg`];
  const out = {
    name: p.name,
    description: p.description,
    longDescription: long(p.name, p.bullets),
    price: p.price,
    category: p.category,
    brand: p.brand,
    species: p.species,
    foodType: p.foodType,
    images,
    featured: p.featured ?? false,
    inStock: (p.stock ?? (p.variants ? p.variants.reduce((s, v) => s + v[3], 0) : 0)) > 0,
    tags: p.tags ?? [],
    ...(p.compareAtPrice != null ? { compareAtPrice: p.compareAtPrice } : {}),
    ...(p.bonusKg != null ? { bonusKg: p.bonusKg } : {}),
    ...(p.stock != null ? { stock: p.stock } : {}),
    ...(p.badge ? { badge: p.badge } : {}),
    ...(p.variants
      ? {
          variants: p.variants.map(([label, price, compareAtPrice, stock, bonusKg]) => ({
            label,
            price,
            stock,
            ...(compareAtPrice != null ? { compareAtPrice } : {}),
            ...(bonusKg != null ? { bonusKg } : {}),
          })),
        }
      : {}),
  };
  return out;
}

